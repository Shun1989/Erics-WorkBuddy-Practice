# ---------- 图 4-1 同一件活，没有技能和有技能 ----------
def fig_4_1():
    lt, li = '没有技能', [
        ('我要说的话', '每次重讲一遍格式、顺序、判定值'),
        ('往返轮数', '5 到 8 轮纠正'),
        ('出错类型', '顺序错、日期格式错、判定值用错'),
        ('换窗口之后', '全部重讲'),
        ('交给同事', '得把要求再复述一遍给同事'),
        ('我花的时间', '单次约 40 分钟'),
    ]
    rt, ri = '有技能', [
        ('我要说的话', '跑月度数据包'),
        ('往返轮数', '通常 1 轮'),
        ('出错类型', '数据本身有问题，这个本来就要人看'),
        ('换窗口之后', '照旧执行'),
        ('交给同事', '把文件发给他放进目录就行'),
        ('我花的时间', '单次约 6 分钟'),
    ]
    return F.compare('同一件活，没有技能和有技能',
                     '技能不提升它的智商，提升的是它的稳定性',
                     lt, li, rt, ri,
                     note='第 4.1 节：从 40 分钟降到 6 分钟，一年十二次就是七个钟头')


