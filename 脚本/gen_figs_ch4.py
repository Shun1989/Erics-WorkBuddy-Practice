# ---------- 图 4-5 技能用不好的四个原因 ----------
def fig_4_5():
    items = [
        ('no', '原因一 写得太抽象',
         '正文全是形容词和原则，没有一条能被验证。修法：把每一句含糊话换成数字、文件名、颜色值、时间点，替换不掉就删掉。'),
        ('no', '原因二 描述和实际不符',
         '该出场不出来，不该出来抢着出来。修法：每次改完正文，让它逐个确认正文里提到的每一个文件路径是否真的存在。'),
        ('no', '原因三 触发词没写对',
         '触发词过窄只写一个说法，或者过宽包了一大片。修法：把同义词全列上，并且一定写上不适用于。'),
        ('no', '原因四 一个技能塞太多事',
         '正文超过 400 行、步骤超过 7 条，每次只完成一部分。修法：按输出物拆，不按主题拆。'),
    ]
    return F.checklist('技能用不好的四个原因',
                       '我手上因为不好用而废弃的技能有十几个，复盘下来逃不出这四个',
                       items,
                       note='第 4.5 节：删掉一句含糊话，技能反而变好')


