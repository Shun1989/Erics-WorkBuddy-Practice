def block(num, title, svg):
    return ('\n![图 %s %s](../../配图/svg/%s)\n\n'
            '*图 %s 作者根据公开资料绘制。*\n' % (num, title, svg, num))


def main():
    byfile = {}
    for fn, anchor, num, title, svg in INS:
        byfile.setdefault(fn, []).append((anchor, num, title, svg))

    ok = 0
    for fn, items in byfile.items():
        p = os.path.join(CH, fn)
        text = io.open(p, encoding='utf-8').read()
        for anchor, num, title, svg in items:
            if num in text:                       # 已插入过则跳过
                print('跳过已存在', num)
                continue
            i = text.find(anchor)
            if i < 0:
                print('锚点未找到', fn, num, repr(anchor[:40]))
                continue
            # 定位锚点所在行的末尾（若锚点是多行，取最后一行末尾）
            j = i + len(anchor)
            nl = text.find('\n', j)
            if nl < 0:
                nl = len(text)
            # 若锚点行末之后紧跟空行或图片块，则插在空行之前
            text = text[:nl] + block(num, title, svg) + text[nl:]
            ok += 1
        io.open(p, 'w', encoding='utf-8').write(text)
        print('已写入', fn, len(items), '张候选')
    print('实际插入', ok, '张')
    return 0 if ok == len(INS) else 1


if __name__ == '__main__':
    sys.exit(main())